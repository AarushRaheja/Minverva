"""The integrator: one script, no model. It runs every round, so what gets audited is what gets delivered."""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

from minerva.bridge.contract import AppContract, render_api_client
from minerva.integrator import host_files as H
from slm.contracts import Artifact, Deliverable, ProjectPlan, integrate
from slm.manager.spec import ProjectSpec
from slm.pipeline.dispatch import SPEC_PATH

ROOT = Path(__file__).resolve().parents[2]
TEMPLATE = ROOT / "templates" / "frontend"
# The frontend agent replaces these kinds. The typed client is replaced by api.ts, which covers every entity.
HOST_KINDS = frozenset({"page", "form", "layout", "client"})
_TEMPLATE_FILES = ("package.json", "package-lock.json", "tsconfig.json", "tailwind.config.cjs", "postcss.config.cjs",
                   "vite.config.ts", "src/main.tsx", "src/AuthGate.tsx")


@dataclass
class Assembled:
    files: dict[str, str]
    deliverable: Deliverable


def _readme(contract: AppContract) -> str:
    entities = ", ".join(e.label for e in contract.entities)
    return f"""# {contract.name}

Generated by Minerva from this brief:

> {contract.brief}
{f"""
Requested look:

> {contract.look}
""" if contract.look else ""}
See `REPORT.md` for what was checked and what was not.

## Run it

Requires Python 3.11+ and Node 22.

```sh
make preview            # http://localhost:8000
```

That installs what is missing, builds the frontend and starts the app. The app sets up its own database when it starts:
with no `DATABASE_URL` it runs a private Postgres in `.data/`, and with one it creates the database if needed and applies
the schema. The private database needs Python 3.11 or 3.12, or Postgres installed. Delete `.data/` to start empty.

To use your own database, or change the port, copy `.env.example` to `.env` and edit it. `make dev` runs Vite with hot
reload on port 5173; keep `make preview` going for the API. Set `APP_ENV=production` when deploying: a missing
`DATABASE_URL` then stops the app instead of starting a preview database.

## What this app does

Signed-in users can list and create {entities}. Each row has a title.

## Known limits

- **Shared data.** Every signed-in user sees every row, because the generated list endpoints do not filter by owner.
- **No edit, delete, or fields other than title.** The trained backend agents do not generate them.
- **One session per user.** Signing in on a second device ends the first session.
- **Not production-hardened.** There is no rate limiting, password reset or CSRF token. Review `src/auth/` first.
"""


def assemble(project_id: str, plan: ProjectPlan, spec: ProjectSpec | None, backend: dict[str, Artifact],
             contract: AppContract, app_tsx: str, index_css: str) -> Assembled:
    """Merge the backend artifacts and the frontend into one tree. The seam checks run on the merged result."""
    deliverable = integrate(project_id, plan, backend, host_kinds=HOST_KINDS)
    files = {f.path: f.content for f in deliverable.files}
    files["src/app.py"] = files["src/app.py"].replace(
        "# Frontend pages are built from src/frontend/ and served as static assets.\n", "").rstrip() + (
        "\n\nfrom src.auth.accounts import router as accounts_router  # noqa: E402\n"
        "from src.database.bootstrap import prepare as prepare_database, shutdown as stop_database  # noqa: E402\n"
        "from src.spa import build_frontend, mount_spa  # noqa: E402\n\n"
        "app.add_event_handler(\"startup\", prepare_database)\n"
        "app.add_event_handler(\"startup\", build_frontend)\n"
        "app.add_event_handler(\"shutdown\", stop_database)\n"
        "app.include_router(accounts_router)\n"
        "mount_spa(app)  # last: its catch-all must not shadow the API\n")
    files.update({
        "src/auth/accounts.py": H.ACCOUNTS,
        "src/spa.py": H.SPA,
        "src/database/migrate.py": H.MIGRATE,
        "src/database/bootstrap.py": H.BOOTSTRAP,
        "src/main.py": H.MAIN,
        "requirements.txt": H.REQUIREMENTS,
        ".env.example": H.ENV_EXAMPLE,
        "Makefile": H.MAKEFILE,
        ".gitignore": H.GITIGNORE,
        "README.md": _readme(contract),
        "frontend/src/api.ts": render_api_client(contract),
        "frontend/src/App.tsx": app_tsx,
        "frontend/src/index.css": index_css,
        "frontend/index.html": (TEMPLATE / "index.html").read_text().replace(
            "{{APP_TITLE}}", contract.name.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")),
    })
    for name in _TEMPLATE_FILES:
        files[f"frontend/{name}"] = (TEMPLATE / name).read_text()
    if spec is not None:
        files[SPEC_PATH] = spec.model_dump_json(indent=2)
    files["BRIEF.json"] = json.dumps({"brief": contract.brief, "look": contract.look, "name": contract.name}, indent=2)
    return Assembled(files=files, deliverable=deliverable)


def write_tree(files: dict[str, str], directory: Path) -> None:
    root = directory.resolve()
    for name, content in files.items():
        target = (root / name).resolve()
        if not target.is_relative_to(root):  # paths come from a model's JSON
            raise ValueError(f"unsafe path from generated artifact: {name!r}")
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content)
